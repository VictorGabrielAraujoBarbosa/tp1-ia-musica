"use strict";

/* Visualizer for the race-reactive generative music system.
 *
 * Master clock is the audio element. Music time -> race time via the sync log
 * (gm-sync/1), so meter-induced bar-length drift is handled for free.
 * See docs/contracts.md for the data schemas. */

const $ = (sel) => document.querySelector(sel);
const clamp = (v, a, b) => Math.min(b, Math.max(a, v));
const lerp = (a, b, t) => a + (b - a) * t;

const ENTITIES = [
  { key: "you", label: "You" },
  { key: "opp", label: "Opponent" },
  { key: "police", label: "Police" },
];
const LAYERS = ["drums", "bass", "pad", "lead"];
const COLORS = { you: "#3dd6ff", opp: "#ff6b6b", police: "#8fa6ff" };

const audio = $("#audio");
const app = {
  bundles: [],
  bundle: null,
  race: null,
  sync: null,
  graph: null,      // { ctx, analyser }
  waveform: false,
  dragging: false,
  chart: null,      // { canvas, ctx, w, h, dpr, pad }
  chartBase: null,  // prerendered offscreen canvas
  scope: null,
};

/* ------------------------------------------------------------------ boot */

async function boot() {
  try {
    const res = await fetch("data/bundles.json", { cache: "no-store" });
    if (!res.ok) throw new Error(`HTTP ${res.status}`);
    app.bundles = (await res.json()).bundles || [];
  } catch (err) {
    fatal("Could not load <code>data/bundles.json</code>. Serve this folder over HTTP, e.g. " +
          "<code>python3 -m http.server</code>, and open the printed URL instead of the file directly.");
    return;
  }

  const picker = $("#bundlePicker");
  picker.innerHTML = "";
  for (const bundle of app.bundles) {
    const btn = document.createElement("button");
    btn.type = "button";
    btn.textContent = bundle.name;
    btn.dataset.id = bundle.id;
    btn.addEventListener("click", () => selectBundle(bundle));
    picker.appendChild(btn);
  }

  if (!app.bundles.length) {
    fatal("No bundles found. Run <code>tools/make_race.py</code> and " +
          "<code>tools/make_demo_bundle.py</code> first.");
    return;
  }
  await selectBundle(app.bundles[0]);
}

function fatal(html) {
  const div = document.createElement("div");
  div.className = "fatal";
  div.innerHTML = html;
  document.querySelector("main").prepend(div);
}

/* --------------------------------------------------------------- bundles */

async function selectBundle(bundle) {
  app.bundle = bundle;
  document.querySelectorAll("#bundlePicker button").forEach((el) =>
    el.classList.toggle("active", el.dataset.id === bundle.id));

  audio.pause();
  audio.currentTime = 0;

  const [race, sync] = await Promise.all([
    fetch(bundle.race, { cache: "no-store" }).then((r) => r.json()),
    fetch(bundle.sync, { cache: "no-store" }).then((r) => r.json()),
  ]);
  app.race = race;
  app.sync = sync;

  $("#bundleSub").textContent = bundle.placeholder
    ? `${bundle.description} — placeholder audio (stand-in sync + click track)`
    : `${bundle.description} — generated by the Markov engine`;

  audio.src = bundle.audio;
  audio.load();

  buildLanes();
  buildLayerList();
  app.chartBase = null;
  resizeCanvases();
  render(0);
}

function buildLanes() {
  const lanes = $("#lanes");
  lanes.innerHTML = "";
  for (const entity of ENTITIES) {
    const lane = document.createElement("div");
    lane.className = `lane ${entity.key}`;
    lane.dataset.key = entity.key;
    lane.innerHTML = `
      <span class="lane-label">${entity.label}</span>
      <div class="lane-track">
        <div class="lane-fill"></div>
        <div class="lane-marker"></div>
      </div>`;
    lanes.appendChild(lane);
  }
}

function buildLayerList() {
  const list = $("#layers");
  list.innerHTML = "";
  for (const name of LAYERS) {
    const li = document.createElement("li");
    li.className = "layer";
    li.dataset.layer = name;
    li.textContent = name;
    list.appendChild(li);
  }
}

/* ------------------------------------------------------------- time math */

function totalMusic() {
  const bars = app.sync.bars;
  const last = bars[bars.length - 1];
  const quarters = (last.meter[0] * 4) / last.meter[1];
  return last.t_music + quarters * (60 / app.sync.bpm);
}

function syncAt(tMusic) {
  const bars = app.sync.bars;
  let lo = 0;
  let hi = bars.length - 1;
  while (lo < hi) {
    const mid = (lo + hi + 1) >> 1;
    if (bars[mid].t_music <= tMusic) lo = mid;
    else hi = mid - 1;
  }
  const b0 = bars[lo];
  const b1 = bars[Math.min(lo + 1, bars.length - 1)];
  const span = Math.max(1e-6, b1.t_music - b0.t_music);
  const f = b1 === b0 ? 1 : clamp((tMusic - b0.t_music) / span, 0, 1);
  return {
    index: lo,
    bar: b0,
    tRace: lerp(b0.t_race, b1.t_race, f),
    tension: lerp(b0.tension, b1.tension, f),
    meter: b0.meter,
    layers: b0.layers,
  };
}

function raceAt(tRace) {
  const samples = app.race.samples;
  const x = clamp(tRace, 0, samples.length - 1);
  const i = Math.floor(x);
  const f = x - i;
  const a = samples[i];
  const b = samples[Math.min(i + 1, samples.length - 1)];

  const merge = (key) => {
    const va = a[key];
    const vb = b[key];
    if (va === null && vb === null) return null;
    if (va === null) return vb;
    if (vb === null) return va;
    return lerp(va, vb, f);
  };

  const you = merge("you");
  const opp = merge("opp");
  const police = merge("police");
  return {
    you,
    opp,
    police,
    gap: you - opp,
    policeDist: police === null ? null : you - police,
  };
}

/* ----------------------------------------------------------------- render */

function render(tMusic) {
  if (!app.sync || !app.race) return;
  const total = totalMusic();
  tMusic = clamp(tMusic, 0, total);

  const sync = syncAt(tMusic);
  const rs = raceAt(sync.tRace);

  updateLanes(rs);
  updateMusicState(sync, rs);

  $("#clock").textContent = `music ${tMusic.toFixed(1)}s · race ${sync.tRace.toFixed(1)}s`;
  $("#barInfo").textContent = `bar ${sync.bar.i + 1}/${app.sync.bars.length} · ${app.sync.bpm} BPM`;

  if (!app.dragging) $("#seek").value = String(Math.round((tMusic / total) * 1000));
  const dur = Number.isFinite(audio.duration) && audio.duration > 0 ? audio.duration : total;
  $("#timeLabel").textContent = `${fmtTime(audio.currentTime)} / ${fmtTime(dur)}`;

  drawChart(sync.tRace);
}

function updateLanes(rs) {
  for (const entity of ENTITIES) {
    const lane = document.querySelector(`.lane[data-key="${entity.key}"]`);
    if (!lane) continue;
    const value = rs[entity.key];
    const inactive = value === null;
    lane.classList.toggle("inactive", inactive);
    if (inactive) continue;
    const pct = clamp(value, 0, 1) * 100;
    lane.querySelector(".lane-fill").style.width = `${pct}%`;
    lane.querySelector(".lane-marker").style.left = `${pct}%`;
  }
}

function updateMusicState(sync, rs) {
  const gapEl = $("#gapValue");
  gapEl.textContent = `${rs.gap >= 0 ? "+" : ""}${rs.gap.toFixed(3)}`;
  gapEl.classList.toggle("ahead", rs.gap >= 0);
  gapEl.classList.toggle("behind", rs.gap < 0);

  $("#policeValue").textContent = rs.policeDist === null ? "—" : rs.policeDist.toFixed(3);
  $("#phaseValue").textContent = Math.max(rs.you, rs.opp).toFixed(3);

  const badge = $("#meterBadge");
  badge.textContent = `${sync.meter[0]}/${sync.meter[1]}`;
  badge.classList.toggle("odd", sync.meter[1] === 8);

  $("#tensionBar").style.width = `${(sync.tension * 100).toFixed(1)}%`;
  $("#tensionValue").textContent = sync.tension.toFixed(2);

  for (const name of LAYERS) {
    const el = document.querySelector(`.layer[data-layer="${name}"]`);
    if (el) el.classList.toggle("on", Boolean(sync.layers[name]));
  }
}

function fmtTime(sec) {
  sec = Math.max(0, Math.round(sec));
  const m = Math.floor(sec / 60);
  return `${m}:${String(sec % 60).padStart(2, "0")}`;
}

/* ---------------------------------------------------------------- canvas */

function fitCanvas(canvas) {
  const dpr = window.devicePixelRatio || 1;
  const w = canvas.clientWidth || 600;
  const h = canvas.clientHeight || 200;
  canvas.width = Math.round(w * dpr);
  canvas.height = Math.round(h * dpr);
  const ctx = canvas.getContext("2d");
  ctx.setTransform(dpr, 0, 0, dpr, 0, 0);
  return { canvas, ctx, w, h, dpr, pad: { l: 38, r: 12, t: 14, b: 24 } };
}

function resizeCanvases() {
  app.chart = fitCanvas($("#chart"));
  app.scope = fitCanvas($("#scope"));
  app.chartBase = null;
  if (app.race) {
    drawChartBase();
    drawChart(audio.currentTime || 0);
  }
}

function drawChartBase() {
  const c = app.chart;
  if (!c || !app.race) return;
  const off = document.createElement("canvas");
  off.width = c.canvas.width;
  off.height = c.canvas.height;
  const ctx = off.getContext("2d");
  ctx.setTransform(c.dpr, 0, 0, c.dpr, 0, 0);

  const { w, h, pad } = c;
  const plotW = w - pad.l - pad.r;
  const plotH = h - pad.t - pad.b;
  const duration = app.race.duration_s;
  const x = (t) => pad.l + (t / duration) * plotW;
  const y = (v) => pad.t + (1 - v) * plotH;

  ctx.font = "10px system-ui, sans-serif";
  ctx.lineWidth = 1;
  for (let g = 0; g <= 4; g++) {
    const gy = pad.t + plotH * (g / 4);
    ctx.strokeStyle = "rgba(255,255,255,.07)";
    ctx.beginPath();
    ctx.moveTo(pad.l, gy);
    ctx.lineTo(w - pad.r, gy);
    ctx.stroke();
    ctx.fillStyle = "#8a94a8";
    ctx.fillText((1 - g / 4).toFixed(2), 4, gy + 3);
  }
  for (let s = 30; s <= duration; s += 30) {
    ctx.fillStyle = "#8a94a8";
    ctx.fillText(`${s}s`, x(s) - 8, h - 7);
  }

  ctx.save();
  ctx.setLineDash([3, 4]);
  for (const ev of app.race.events || []) {
    ctx.strokeStyle = "rgba(143,166,255,.45)";
    ctx.beginPath();
    ctx.moveTo(x(ev.t), pad.t);
    ctx.lineTo(x(ev.t), pad.t + plotH);
    ctx.stroke();
    ctx.fillStyle = "rgba(143,166,255,.85)";
    ctx.fillText(ev.type.replace(/_/g, " "), x(ev.t) + 3, pad.t + 10);
  }
  ctx.restore();

  for (const key of ["you", "opp", "police"]) {
    ctx.save();
    ctx.strokeStyle = COLORS[key];
    ctx.lineWidth = key === "police" ? 1.5 : 2;
    if (key === "police") ctx.setLineDash([5, 4]);
    ctx.beginPath();
    let started = false;
    for (const sample of app.race.samples) {
      const v = sample[key];
      if (v === null) {
        started = false;
        continue;
      }
      const px = x(sample.t);
      const py = y(v);
      if (!started) {
        ctx.moveTo(px, py);
        started = true;
      } else {
        ctx.lineTo(px, py);
      }
    }
    ctx.stroke();
    ctx.restore();
  }

  app.chartBase = off;
}

function drawChart(tRace) {
  const c = app.chart;
  if (!c || !app.race) return;
  if (!app.chartBase) drawChartBase();

  c.ctx.clearRect(0, 0, c.w, c.h);
  if (app.chartBase) c.ctx.drawImage(app.chartBase, 0, 0, c.w, c.h);

  const { w, h, pad } = c;
  const plotW = w - pad.l - pad.r;
  const plotH = h - pad.t - pad.b;
  const px = pad.l + clamp(tRace / app.race.duration_s, 0, 1) * plotW;

  c.ctx.strokeStyle = "rgba(255,255,255,.8)";
  c.ctx.lineWidth = 1;
  c.ctx.beginPath();
  c.ctx.moveTo(px, pad.t);
  c.ctx.lineTo(px, h - pad.b);
  c.ctx.stroke();

  const rs = raceAt(tRace);
  for (const key of ["you", "opp", "police"]) {
    if (rs[key] === null) continue;
    const py = pad.t + (1 - rs[key]) * plotH;
    c.ctx.fillStyle = COLORS[key];
    c.ctx.beginPath();
    c.ctx.arc(px, py, 3, 0, Math.PI * 2);
    c.ctx.fill();
  }
}

function drawScope() {
  const c = app.scope;
  if (!c) return;
  const { ctx, w, h } = c;
  ctx.clearRect(0, 0, w, h);

  const analyser = app.graph && app.graph.analyser;
  if (!analyser) {
    ctx.fillStyle = "#5c6780";
    ctx.font = "12px system-ui, sans-serif";
    ctx.fillText("Press Play to start audio", 12, h / 2 + 4);
    return;
  }

  if (app.waveform) {
    const data = new Uint8Array(analyser.fftSize);
    analyser.getByteTimeDomainData(data);
    ctx.beginPath();
    for (let i = 0; i < data.length; i++) {
      const x = (i / (data.length - 1)) * w;
      const y = h / 2 - ((data[i] - 128) / 128) * (h / 2 - 6);
      if (i === 0) ctx.moveTo(x, y);
      else ctx.lineTo(x, y);
    }
    ctx.strokeStyle = COLORS.you;
    ctx.lineWidth = 1.5;
    ctx.stroke();
    return;
  }

  const bins = 72;
  const gap = 2;
  const barW = (w - gap * (bins - 1)) / bins;
  const data = new Uint8Array(analyser.frequencyBinCount);
  analyser.getByteFrequencyData(data);
  const step = Math.max(1, Math.floor(data.length / bins));
  for (let i = 0; i < bins; i++) {
    let sum = 0;
    for (let k = 0; k < step; k++) sum += data[i * step + k] || 0;
    const value = sum / step / 255;
    const barH = Math.max(2, value * (h - 8));
    const grad = ctx.createLinearGradient(0, h, 0, h - barH);
    grad.addColorStop(0, "#1d5f8a");
    grad.addColorStop(1, "#3dd6ff");
    ctx.fillStyle = grad;
    ctx.fillRect(i * (barW + gap), h - barH, barW, barH);
  }
}

/* ----------------------------------------------------------------- audio */

function ensureAudioGraph() {
  if (app.graph) return app.graph;
  const Ctx = window.AudioContext || window.webkitAudioContext;
  const ctx = new Ctx();
  const source = ctx.createMediaElementSource(audio);
  const analyser = ctx.createAnalyser();
  analyser.fftSize = 2048;
  analyser.smoothingTimeConstant = 0.82;
  source.connect(analyser);
  analyser.connect(ctx.destination);
  app.graph = { ctx, analyser };
  return app.graph;
}

async function togglePlay() {
  if (!app.bundle) return;
  const graph = ensureAudioGraph();
  if (graph.ctx.state === "suspended") await graph.ctx.resume();
  if (audio.paused) {
    audio.play().catch(() => {});
  } else {
    audio.pause();
  }
}

/* ------------------------------------------------------------------ wiring */

function wireEvents() {
  $("#playButton").addEventListener("click", togglePlay);

  $("#replayButton").addEventListener("click", async () => {
    const graph = ensureAudioGraph();
    if (graph.ctx.state === "suspended") await graph.ctx.resume();
    audio.currentTime = 0;
    render(0);
    audio.play().catch(() => {});
  });

  $("#scopeToggle").addEventListener("click", (event) => {
    app.waveform = !app.waveform;
    event.target.textContent = app.waveform ? "Spectrum" : "Waveform";
  });

  const seek = $("#seek");
  seek.addEventListener("pointerdown", () => { app.dragging = true; });
  window.addEventListener("pointerup", () => { app.dragging = false; });
  seek.addEventListener("input", () => {
    const t = (Number(seek.value) / 1000) * totalMusic();
    if (Number.isFinite(audio.duration) && audio.duration > 0) {
      audio.currentTime = clamp(t, 0, Math.max(0, audio.duration - 0.05));
    }
    render(t);
  });

  audio.addEventListener("play", () => { $("#playButton").textContent = "Pause"; });
  audio.addEventListener("pause", () => { $("#playButton").textContent = "Play"; });
  audio.addEventListener("ended", () => {
    $("#playButton").textContent = "Play";
    render(totalMusic());
  });

  window.addEventListener("resize", () => {
    resizeCanvases();
    if (app.sync) render(audio.currentTime);
  });
}

function loop() {
  if (app.sync) {
    if (!audio.paused && !app.dragging) render(audio.currentTime);
    drawScope();
  }
  requestAnimationFrame(loop);
}

wireEvents();
boot();
requestAnimationFrame(loop);
